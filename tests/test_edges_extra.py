"""Edge cases: coercion, warnings, failure accounting and CLI exits."""

from __future__ import annotations

import io
import json
from typing import Any

import pytest

from esib import BulkError, Client, Config, FakeCluster, IndexManager, encode_bulk, infer_mappings
from esib.bulk import BulkIndexer, BulkOutcome
from esib.cli import main
from esib.client import _body_json, _retry_after
from esib.errors import TransportError
from esib.transport import Response, StubTransport


def _client(transport: Any) -> Client:
    return Client(Config(base_url="http://fake:9200"), transport=transport, sleep=lambda _d: None)


def test_retry_after_ignores_unparsable_headers() -> None:
    reply = Response(status=429, headers={"Retry-After": "soon"}, body=b"{}")
    assert _retry_after(reply) is None


def test_body_json_falls_back_to_raw_text() -> None:
    reply = Response(status=500, headers={}, body=b"<html>oops</html>")
    assert _body_json(reply)["raw"].startswith("<html>")


def test_send_encodes_strings_and_rejects_exotic_bodies() -> None:
    cluster = FakeCluster()
    client = _client(cluster)
    reply = client.send("PUT", "/notes", body='{"settings": {}}', content_type="application/json")
    assert reply.status == 200
    with pytest.raises(TypeError):
        client.send("PUT", "/notes", body=object())


def test_client_closes_quietly_and_works_as_a_context_manager() -> None:
    with _client(FakeCluster()) as client:
        assert client.info()["tagline"] == "You Know, for Search"
    client.close()


def test_exists_maps_404_to_false(manager_cluster: FakeCluster) -> None:
    manager_cluster.indices.clear()
    client = _client(manager_cluster)
    assert client.exists("/nothing") is False


def test_bulk_reply_that_is_not_an_object_is_a_transport_error() -> None:
    stub = StubTransport()
    stub.fallback = Response(status=200, headers={}, body=b"[1, 2, 3]")
    client = _client(stub)
    with pytest.raises(TransportError, match="unexpected bulk response"):
        client.bulk(b'{"index":{"_id":"1"}}\n{"a":1}\n')


def test_send_honours_an_explicit_attempt_budget(
    manager: IndexManager, cluster: FakeCluster
) -> None:
    cluster.add_fault(503, path_contains="/_cluster/health", times=5)
    reply = manager.client.send("GET", "/_cluster/health", attempts=1)
    assert reply.status == 503
    assert manager.client.stats.retries == 0


def test_missing_id_is_reported_not_silently_autogenerated(manager: IndexManager) -> None:
    manager.create("books")
    outcome = BulkIndexer(manager.client).load(
        "books",
        [{"title": "Dune"}, {"id": "2", "title": "Emma"}],
        id_field="id",
        on_failure="collect",
    )
    assert outcome.failed == 1
    assert outcome.indexed == 1
    assert outcome.failures[0].error_type == "missing_id"


def test_encode_bulk_rejects_unknown_actions_and_non_objects() -> None:
    with pytest.raises(BulkError, match="unsupported bulk action"):
        encode_bulk("books", [{"a": 1}], action="upsert")
    with pytest.raises(BulkError, match="not an object"):
        encode_bulk("books", [{"a": 1}, ["nope"]])  # type: ignore[list-item]


def test_delete_action_sends_only_the_metadata_line() -> None:
    body = encode_bulk("books", [{"a": 1}], id_field="a", action="delete")
    assert body.count(b"\n") == 1
    assert b'"delete"' in body


def test_accounting_skips_items_that_are_not_objects() -> None:
    indexer = BulkIndexer(_client(FakeCluster()))
    outcome = BulkOutcome()
    pending = indexer._account(
        ["garbage"], encode_bulk("books", [{"a": 1}]), outcome, allow_retry=True
    )
    assert pending == []
    assert outcome.indexed == 0


def test_raise_on_failure_names_the_first_reason(manager: IndexManager) -> None:
    manager.create(
        "strict", mappings={"dynamic": "strict", "properties": {"id": {"type": "keyword"}}}
    )
    with pytest.raises(BulkError, match=r"mapper_parsing_exception|strict"):
        manager.load("strict", [{"id": "1", "x": 2}], id_field="id")


def test_boolean_and_string_mix_becomes_keyword() -> None:
    inferred = infer_mappings([{"flag": True}, {"flag": "yes please"}])
    assert inferred.mappings()["properties"]["flag"] == {"type": "keyword"}
    assert any("booleans and strings" in warning for warning in inferred.warnings)


def test_number_and_boolean_mix_becomes_text_with_a_warning() -> None:
    inferred = infer_mappings([{"v": 3}, {"v": True}])
    assert inferred.mappings()["properties"]["v"]["type"] == "text"
    assert any("mixes several kinds" in warning for warning in inferred.warnings)


def test_keyword_length_threshold_is_configurable() -> None:
    rows = [{"code": "a" * 40} for _ in range(5)]
    short = infer_mappings(rows, keyword_max_length=8)
    long = infer_mappings(rows, keyword_max_length=64)
    assert short.mappings()["properties"]["code"]["type"] == "text"
    assert long.mappings()["properties"]["code"]["type"] == "keyword"


def test_date_detection_can_be_switched_off() -> None:
    rows = [{"when": "2026-01-02"}]
    assert infer_mappings(rows).mappings()["properties"]["when"] == {"type": "date"}
    assert infer_mappings(rows, date_detection=False).mappings()["properties"]["when"]["type"] == (
        "keyword"
    )


def test_object_that_is_sometimes_a_scalar_is_still_an_object() -> None:
    inferred = infer_mappings([{"address": {"city": "Porto"}}, {"address": "Porto"}])
    spec = inferred.mappings()["properties"]["address"]
    assert spec["type"] == "object"
    assert any("sometimes an object" in warning for warning in inferred.warnings)


def test_alias_cannot_be_added_to_a_missing_index() -> None:
    cluster = FakeCluster()
    client = _client(cluster)
    with pytest.raises(Exception, match="no such index"):
        client.post("/_aliases", {"actions": [{"add": {"index": "ghost", "alias": "live"}}]})


def test_alias_actions_validate_their_payload() -> None:
    cluster = FakeCluster()
    client = _client(cluster)
    client.put("/books", {})
    with pytest.raises(Exception, match="actions must be an array"):
        client.post("/_aliases", {"actions": "nope"})
    with pytest.raises(Exception, match="unknown alias action"):
        client.post("/_aliases", {"actions": [{"swap": {"index": "books", "alias": "live"}}]})
    with pytest.raises(Exception, match="index and alias are required"):
        client.post("/_aliases", {"actions": [{"add": {"index": "books"}}]})


def test_an_index_named_like_an_alias_cannot_be_created() -> None:
    cluster = FakeCluster()
    client = _client(cluster)
    client.put("/books-v1", {})
    client.post("/_aliases", {"actions": [{"add": {"index": "books-v1", "alias": "books"}}]})
    with pytest.raises(Exception, match="is an alias"):
        client.put("/books", {})


