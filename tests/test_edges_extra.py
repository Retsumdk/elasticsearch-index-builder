def test_cli_search_with_sort_uses_search_after(tmp_path: Any) -> None:
    cluster = FakeCluster()
    client = _client(cluster)
    source = tmp_path / "rows.ndjson"
    source.write_text("\n".join(json.dumps({"id": f"r{index}"}) for index in range(4)) + "\n")
    out = io.StringIO()
    client.put("/rows", {})
    IndexManager(client).load("rows", ({"id": f"r{index}"} for index in range(4)), id_field="id")
    code = main(
        ["search", "rows", "--sort", "id:asc", "--size", "2", "--pages", "5"],
        stream=out,
        client=client,
    )
    assert code == 0
    assert "4 documents" in out.getvalue()


def test_cli_keyboard_interrupt_is_reported_as_130(monkeypatch: Any) -> None:
    def boom(args: Any, out: Any) -> int:
        raise KeyboardInterrupt

    client = _client(FakeCluster())
    monkeypatch.setattr("esib.cli._cmd_health", boom)
    out = io.StringIO()
    assert main(["health"], stream=out, client=client) == 130


